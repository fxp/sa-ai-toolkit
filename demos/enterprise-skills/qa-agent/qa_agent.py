    if company:
        print(f"  🏭 当前企业：{company}")
    print("  📋 知识库：8大类共35+高频问题")
    print("  💡 输入问题，Agent实时回答")
    print("█" * 60)

    # 展示问题分类
    print("\n  📊 问题分类覆盖：")
    for cat_id, cat in FAQ_KNOWLEDGE_BASE.items():
        print(f"     {cat['频率'][:5]}  {cat['分类说明']}（{cat['典型提问者']}）")

