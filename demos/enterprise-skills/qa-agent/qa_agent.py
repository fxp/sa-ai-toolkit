def build_system_prompt(company: str = "") -> str:
    """构建Agent的System Prompt，灌入FAQ知识库"""

    # 把知识库压缩为文本
    kb_text = ""
    for cat_id, cat in FAQ_KNOWLEDGE_BASE.items():
        kb_text += f"\n\n## {cat['分类说明']}\n"
        for item in cat["问答"]:
            kb_text += f"\nQ: {item['q']}\nA: {item['a']}\n核心要点: {item['关键点']}\n"

    company_ctx = f"\n当前培训企业：{company}\n请在回答中尽量结合该企业的具体情况。" if company else ""

    return f"""你是一位资深的企业AI培训讲师助理。你的任务是在培训现场回答学员的提问。

以下是从30+场企业AI培训中提炼的高频问题和标准回答，请以此为基础回答：
{kb_text}
{company_ctx}

回答规则：
1. **简洁有力**：每个回答控制在3-5句话，不要长篇大论
2. **用类比**：把技术概念翻译成业务语言（"就像Excel之于会计"）
3. **给结论**：先说结论，再解释为什么
4. **说人话**：不要用"赋能""抓手"等空洞词汇
5. **诚实**：不确定的说"这个我不确定"，不要编
6. **有态度**：该推荐就推荐，该劝退就劝退（"这个场景AI目前做不好，建议先等等"）
7. 如果问题超出知识库范围，基于你的通用知识回答，但标注"[超出FAQ范围，以下为通用建议]"
8. 每个回答末尾附 **💡 一句话要点**"""


def classify_question(question: str) -> str:
    """用关键词快速分类问题"""
    q = question.lower()
    if any(w in q for w in ["安全", "保密", "涉密", "隐私", "合规", "国产化", "知识产权", "过审"]):
        return "C2_安全合规"
    if any(w in q for w in ["多少钱", "投入", "预算", "ROI", "成本", "费用", "招人"]):
        return "C3_成本投入"
    if any(w in q for w in ["怎么开始", "先做什么", "落地", "Dify", "Coze", "集成", "推广", "配合"]):
        return "C4_落地路径"
    if any(w in q for w in ["取代", "失业", "裁员", "影响", "学编程", "岗位"]):
        return "C5_岗位影响"
    if any(w in q for w in ["GPU", "模型", "选哪个", "RAG", "微调", "Agent", "MCP", "工作流"]):
        return "C6_技术选型"
    if any(w in q for w in ["质检", "图纸", "写代码", "翻译", "客服", "排程"]):
        return "C7_具体场景"
    if any(w in q for w in ["战略", "组织", "部门", "衡量", "落后", "过时"]):
        return "C8_战略与组织"
    return "C1_能力边界"  # 默认


def try_faq_match(question: str) -> str | None:
    """尝试从FAQ中精确匹配"""
    q = question.strip().rstrip("？?。.")
    for cat_id, cat in FAQ_KNOWLEDGE_BASE.items():
        for item in cat["问答"]:
            faq_q = item["q"].rstrip("？?。.")
            # 简单相似度：包含关键词
            overlap = sum(1 for w in faq_q if len(w) > 1 and w in q)
            if overlap > len(faq_q) * 0.3 or q in faq_q or faq_q in q:
                return f"{item['a']}\n\n💡 {item['关键点']}"
    return None


def agent_answer(question: str, company: str = "", history: list = None) -> str:
    """Agent回答问题：先查FAQ，查不到则调用LLM"""

    # 1. 尝试FAQ精确匹配
    faq_hit = try_faq_match(question)

    # 2. 分类问题
    category = classify_question(question)
    cat_info = FAQ_KNOWLEDGE_BASE.get(category, {})

    # 3. 构建messages
    messages = [{"role": "system", "content": build_system_prompt(company)}]

    if history:
        messages.extend(history[-6:])  # 保留最近3轮对话

    # 如果FAQ匹配到，让LLM基于匹配结果润色
    if faq_hit:
        messages.append({
            "role": "user",
            "content": f"""学员提问：「{question}」

我在FAQ知识库中找到了相关回答：
{faq_hit}

请基于这个回答，用口语化的方式重新组织语言回答学员。
要求简洁（3-5句话），结尾附 💡 一句话要点。
如果学员的问题与FAQ不完全匹配，请适当调整和补充。"""
        })
    else:
        messages.append({
            "role": "user",
            "content": f"学员提问：「{question}」\n\n问题分类：{cat_info.get('分类说明', '通用')}\n请回答。"
        })

    resp = client.chat.completions.create(
        model=MODEL,
        messages=messages,
        max_tokens=500,
        temperature=0.3,
    )
    return resp.choices[0].message.content.strip()


def stream_print(text: str, delay: float = 0.012):
    for ch in text:
        print(ch, end="", flush=True)
        time.sleep(delay)
    print()


