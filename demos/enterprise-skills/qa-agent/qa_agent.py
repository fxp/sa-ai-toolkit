    parser.add_argument("--faq", action="store_true", help="生成完整FAQ文档")
    parser.add_argument("--company", type=str, default="", help="企业名称（提供上下文）")
    args = parser.parse_args()

    company = args.company

    # ── FAQ文档生成模式 ──
    if args.faq:
        doc = generate_faq_doc(company)
        outfile = f"{company + '-' if company else ''}培训FAQ.md"
        script_dir = os.path.dirname(os.path.abspath(__file__))
        outpath = os.path.join(script_dir, outfile)
